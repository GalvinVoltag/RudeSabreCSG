#if UNITY_EDITOR || RUNTIME_CSG
using System.Collections.Generic;
using UnityEngine;

namespace Sabresaurus.SabreCSG
{
    /// <summary>
    /// Decides which transform's meshes each polygon is built into when meshes are split per brush or group.
    /// </summary>
    internal static class MeshOwnerResolver
    {
        // How far behind a carved face to look for the solid it was carved out of
        private const float CarvedSolidProbeDepth = 0.01f;

        /// <summary>
        /// Returns the owner of every polygon, indexed by polygon ID, or null when meshes are not being split.
        /// </summary>
        internal static Transform[] Resolve(List<Brush> brushes, PolygonEntry[] polygonIndex, MeshSplitMode splitMode, Transform modelRoot)
        {
            if (splitMode == MeshSplitMode.PerMaterial)
            {
                return null;
            }

            Transform[] brushOwners = GetBrushOwners(brushes, splitMode, modelRoot);
            Transform[] polygonOwners = new Transform[polygonIndex.Length];

            for (int brushIndex = 0; brushIndex < brushes.Count; brushIndex++)
            {
                if (brushes[brushIndex] == null)
                {
                    continue;
                }

                foreach (int polygonID in brushes[brushIndex].GetPolygonIDs())
                {
                    if (polygonID >= 0 && polygonID < polygonOwners.Length)
                    {
                        int owningBrushIndex = GetOwningBrushIndex(brushes, brushIndex, polygonIndex[polygonID]);
                        polygonOwners[polygonID] = brushOwners[owningBrushIndex];
                    }
                }
            }

            return polygonOwners;
        }

        private static Transform[] GetBrushOwners(List<Brush> brushes, MeshSplitMode splitMode, Transform modelRoot)
        {
            Transform[] owners = new Transform[brushes.Count];

            for (int i = 0; i < brushes.Count; i++)
            {
                if (brushes[i] != null)
                {
                    owners[i] = GetOwner(brushes[i], splitMode, modelRoot);
                }
            }

            return owners;
        }

        private static Transform GetOwner(Brush brush, MeshSplitMode splitMode, Transform modelRoot)
        {
            Transform brushTransform = GetControllingBrush(brush).transform;

            if (splitMode == MeshSplitMode.PerGroup)
            {
                Transform group = FindEnclosingGroup(brushTransform, modelRoot);
                if (group != null)
                {
                    return group;
                }
            }

            return brushTransform;
        }

        // The brushes generated by a compound brush are treated as one brush, the compound brush
        private static BrushBase GetControllingBrush(Brush brush)
        {
            PrimitiveBrush primitiveBrush = brush as PrimitiveBrush;

            if (primitiveBrush != null && primitiveBrush.BrushController != null)
            {
                return primitiveBrush.BrushController;
            }

            return brush;
        }

        private static Transform FindEnclosingGroup(Transform child, Transform modelRoot)
        {
            for (Transform parent = child.parent; parent != null && parent != modelRoot; parent = parent.parent)
            {
                if (parent.GetComponent<GroupBrush>() != null)
                {
                    return parent;
                }
            }

            return null;
        }

        // Faces carved by a subtractive brush are built from that brush's own polygons,
        // but they are part of the additive brush that was carved
        private static int GetOwningBrushIndex(List<Brush> brushes, int brushIndex, PolygonEntry entry)
        {
            if (brushes[brushIndex].Mode != CSGMode.Subtract)
            {
                return brushIndex;
            }

            int carvedBrushIndex = FindCarvedBrushIndex(brushes, brushIndex, entry);
            return carvedBrushIndex >= 0 ? carvedBrushIndex : brushIndex;
        }

        // Finds the earlier additive brush containing most of the carved face's area, or -1 if there isn't one
        private static int FindCarvedBrushIndex(List<Brush> brushes, int subtractiveBrushIndex, PolygonEntry entry)
        {
            if (!PolygonEntry.IsValid(entry) || entry.Triangles == null)
            {
                return -1;
            }

            // Only brushes before the subtractive brush can be carved by it
            float[] carvedAreas = new float[subtractiveBrushIndex];

            for (int i = 0; i + 2 < entry.Triangles.Length; i += 3)
            {
                Vector3 a = entry.Positions[entry.Triangles[i]];
                Vector3 b = entry.Positions[entry.Triangles[i + 1]];
                Vector3 c = entry.Positions[entry.Triangles[i + 2]];

                // Faces point away from the solid, and the cross product's length is twice the triangle's area
                Vector3 faceNormal = Vector3.Cross(b - a, c - a);
                float doubleArea = faceNormal.magnitude;
                if (doubleArea <= 0f)
                {
                    continue;
                }

                Vector3 probePoint = (a + b + c) / 3f - faceNormal / doubleArea * CarvedSolidProbeDepth;

                for (int candidate = 0; candidate < subtractiveBrushIndex; candidate++)
                {
                    if (CanBeCarved(brushes[candidate])
                        && GeometryHelper.PolyhedronContainsPoint(brushes[candidate].BrushCache.Polygons, probePoint))
                    {
                        carvedAreas[candidate] += doubleArea;
                    }
                }
            }

            return IndexOfLargest(carvedAreas);
        }

        private static bool CanBeCarved(Brush brush)
        {
            return brush != null && brush.Mode == CSGMode.Add && !brush.IsNoCSG;
        }

        private static int IndexOfLargest(float[] values)
        {
            int largestIndex = -1;
            float largestValue = 0f;

            for (int i = 0; i < values.Length; i++)
            {
                if (values[i] > largestValue)
                {
                    largestValue = values[i];
                    largestIndex = i;
                }
            }

            return largestIndex;
        }
    }
}
#endif
